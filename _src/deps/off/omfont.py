GAP=0.213
def glyph_svg(ch, x, y, cell, fill, gap=GAP):
    rows=G.get(ch)
    if rows is None: return "", 3*(cell+cell*gap)
    p=cell*(1+gap); o=""
    for r,row in enumerate(rows):
        for c,v in enumerate(row):
            if v==".": continue
            px=x+c*p; py=y+r*p
            if v=="#":
                o+=f'<rect x="{px:.2f}" y="{py:.2f}" width="{cell:.2f}" height="{cell:.2f}" fill="{fill}"/>'
            else:
                q={"1":f"M{px+cell:.2f} {py:.2f} L{px+cell:.2f} {py+cell:.2f} L{px:.2f} {py+cell:.2f} Z",
                   "2":f"M{px:.2f} {py:.2f} L{px+cell:.2f} {py+cell:.2f} L{px:.2f} {py+cell:.2f} Z",
                   "3":f"M{px:.2f} {py:.2f} L{px+cell:.2f} {py:.2f} L{px+cell:.2f} {py+cell:.2f} Z",
                   "4":f"M{px:.2f} {py:.2f} L{px+cell:.2f} {py:.2f} L{px:.2f} {py+cell:.2f} Z"}[v]
                o+=f'<path d="{q}" fill="{fill}"/>'
    wd=len(rows[0])
    return o, wd*p - cell*gap
def text_svg(s, x, y, cell, fill, tracking=1.17, gap=GAP):
    o=""; cx=x
    for ch in s:
        if ch==" ": cx+=cell*1.6; continue
        g,w=glyph_svg(ch.upper(),cx,y,cell,fill,gap)
        o+=g; cx+=w+cell*tracking
    return o, cx-x-cell*tracking
def text_width(s, cell, tracking=1.17, gap=GAP):
    p=cell*(1+gap); cx=0
    for ch in s:
        if ch==" ": cx+=cell*1.6; continue
        rows=G.get(ch.upper())
        w=len(rows[0]) if rows else 3
        cx+=w*p-cell*gap+cell*tracking
    return cx-cell*tracking
